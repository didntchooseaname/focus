fn set(
    words: &'static [&'static str],
    cell: &'static OnceLock<HashSet<&'static str>>,
) -> &'static HashSet<&'static str> {
    cell.get_or_init(|| words.iter().copied().collect())
}

pub(super) fn is_unix_command(word: &str) -> bool {
    static CELL: OnceLock<HashSet<&'static str>> = OnceLock::new();
    set(UNIX, &CELL).contains(word)
}

pub(super) fn is_windows_command(word: &str) -> bool {
    static CELL: OnceLock<HashSet<&'static str>> = OnceLock::new();
    set(WINDOWS, &CELL).contains(word.trim_end_matches(".exe"))
}
